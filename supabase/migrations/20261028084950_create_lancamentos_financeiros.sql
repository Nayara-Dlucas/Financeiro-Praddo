INSERT INTO public.lancamentos_financeiros
  (id, user_id, data, tipo, categoria, descricao, forma, conta_id, entrada, saida, origem)
SELECT
  (e.item->>'id')::bigint,
  '3375e0a8-77f8-4c03-96c6-307c7e852e1b'::uuid,
  (e.item->>'data')::date,
  CASE
    WHEN COALESCE(NULLIF(e.item->>'saida','')::numeric,0) > 0 THEN 'saida'
    WHEN lower(COALESCE(e.item->>'categoria','')) LIKE 'venda%' THEN 'venda'
    ELSE 'receita'
  END,
  COALESCE(NULLIF(e.item->>'categoria',''),'Outras receitas'),
  COALESCE(NULLIF(e.item->>'descricao',''),'Lançamento legado'),
  e.item->>'forma',
  CASE WHEN jsonb_typeof(e.item->'contaId') = 'number' THEN (e.item->>'contaId')::bigint ELSE NULL END,
  COALESCE(NULLIF(e.item->>'entrada','')::numeric,0),
  COALESCE(NULLIF(e.item->>'saida','')::numeric,0),
  'legado'
FROM public.app_data a
CROSS JOIN LATERAL jsonb_array_elements(
  CASE WHEN jsonb_typeof(a.value) = 'array' THEN a.value ELSE '[]'::jsonb END
) AS e(item)
WHERE a.key = 'fluxo_caixa_lancamentos'
ON CONFLICT (id) DO NOTHING;

SELECT setval(
  pg_get_serial_sequence('public.lancamentos_financeiros','id'),
  GREATEST(COALESCE((SELECT max(id) FROM public.lancamentos_financeiros),1),1),
  true
);
