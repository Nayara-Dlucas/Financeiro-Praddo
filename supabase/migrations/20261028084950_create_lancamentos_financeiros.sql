CREATE TABLE IF NOT EXISTS public.lancamentos_financeiros (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid(),
  data date NOT NULL,
  tipo text NOT NULL CHECK (tipo IN ('venda','saida','receita','ajuste')),
  categoria text NOT NULL,
  descricao text NOT NULL,
  forma text,
  conta_id bigint,
  conta_nome text,
  entrada numeric(14,2) NOT NULL DEFAULT 0 CHECK (entrada >= 0),
  saida numeric(14,2) NOT NULL DEFAULT 0 CHECK (saida >= 0),
  canal text,
  cliente text,
  observacoes text,
  origem text NOT NULL DEFAULT 'painel' CHECK (origem IN ('painel','chat','importacao','legado')),
  idempotency_key uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT lancamentos_financeiros_entrada_saida_check CHECK (NOT (entrada > 0 AND saida > 0)),
  CONSTRAINT lancamentos_financeiros_idempotency_unique UNIQUE (user_id, idempotency_key)
);

CREATE INDEX IF NOT EXISTS lancamentos_financeiros_user_data_idx
  ON public.lancamentos_financeiros (user_id, data DESC)
  WHERE deleted_at IS NULL;

ALTER TABLE public.lancamentos_financeiros ENABLE ROW LEVEL SECURITY;

